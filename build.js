/*
 * build.js — zero-dependency bundler for Deutschstudio.
 * Scans content/wortschatz/<level>/<date>.json and writes app/data.js
 * as a global (window.DECK) so the app works both locally (file://) and on Vercel.
 *
 * Add a new meeting: drop a JSON file in content/wortschatz/<level>/ and run `node build.js`
 * (on Vercel this runs automatically on every push).
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const CONTENT = path.join(ROOT, 'content', 'wortschatz');
const OUT = path.join(ROOT, 'app', 'data.js');

function readContent(dir) {
  const files = [];
  if (!fs.existsSync(dir)) return files;
  for (const level of fs.readdirSync(dir).sort()) {
    const levelDir = path.join(dir, level);
    if (!fs.statSync(levelDir).isDirectory()) continue;
    for (const name of fs.readdirSync(levelDir).sort()) {
      if (!name.toLowerCase().endsWith('.json')) continue;
      const full = path.join(levelDir, name);
      try {
        const data = JSON.parse(fs.readFileSync(full, 'utf8'));
        files.push({ rel: path.relative(ROOT, full).replace(/\\/g, '/'), data });
      } catch (e) {
        console.error('  ! SKIPPED invalid JSON:', path.relative(ROOT, full), '->', e.message);
      }
    }
  }
  return files;
}

const files = readContent(CONTENT);
const words = [];
const meetings = [];
const seen = new Set();
const errors = [];
const ALLOWED_MODI = ["mc", "tippen", "artikel"];

for (const { rel, data } of files) {
  const meta = {
    klasse: data.class || '?',
    level: data.level || '?',
    meeting: data.meeting || '?',
    topic: data.topic || '',
  };
  const list = Array.isArray(data.words) ? data.words : [];
  let added = 0;
  for (const w of list) {
    if (!w || !w.id || !w.de) continue;
    if (seen.has(w.id)) {
      console.error('  ! DUPLICATE id skipped:', w.id, '(' + rel + ')');
      continue;
    }
    seen.add(w.id);
    if (!Array.isArray(w.modi)) {
      errors.push(rel + " / " + w.id + ': `modi` fehlt oder ist kein Array');
    } else {
      for (const m of w.modi) {
        if (ALLOWED_MODI.indexOf(m) < 0) errors.push(rel + " / " + w.id + ': ungueltiger modi-Wert "' + m + '" (erlaubt: mc, tippen, artikel)');
      }
      if (w.modi.indexOf("artikel") >= 0 && !/^(der|die|das)$/.test(w.artikel || "")) {
        errors.push(rel + " / " + w.id + ': modi "artikel", aber Feld artikel ist nicht der/die/das');
      }
      if (w.typ === "Wortfeld" && w.modi.length > 0) {
        errors.push(rel + " / " + w.id + ': typ "Wortfeld" muss modi: [] haben (nur Karteikarten)');
      }
    }
    if (["Nomen", "Verb", "Adjektiv", "Adverb", "Redewendung", "Wendung", "Wortfeld"].indexOf(w.typ) < 0) {
      errors.push(rel + " / " + w.id + ': ungueltiger typ-Wert "' + w.typ + '"');
    }
    words.push(Object.assign({}, w, {
      _klasse: meta.klasse, _level: meta.level, _meeting: meta.meeting, _topic: meta.topic,
    }));
    added++;
  }
  meetings.push(Object.assign({}, meta, { count: added, source: rel }));
}

if (errors.length) {
  console.error("\nBUILD FEHLGESCHLAGEN — " + errors.length + " Schema-Fehler (modi):");
  errors.forEach(function (e) { console.error("  ! " + e); });
  console.error("\nJede Karte braucht ein gueltiges `modi`-Array (mc | tippen | artikel; [] = nur Karteikarten).");
  process.exit(1);
}

meetings.sort((a, b) => (a.klasse + a.meeting).localeCompare(b.klasse + b.meeting));

const payload = {
  generatedAt: new Date().toISOString(),
  wordCount: words.length,
  meetingCount: meetings.length,
  meetings,
  words,
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  '/* AUTO-GENERATED by build.js — do not edit by hand. */\n' +
  'window.DECK = ' + JSON.stringify(payload) + ';\n',
  'utf8'
);

console.log('build ok: ' + words.length + ' words from ' + files.length + ' files across ' +
  meetings.length + ' meetings -> ' + path.relative(ROOT, OUT));
